CREATE TABLE cliente (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre varchar(120) NOT NULL, documento varchar(30) NOT NULL UNIQUE
);
CREATE TABLE punto_venta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(10) NOT NULL UNIQUE, descripcion varchar(100) NOT NULL
);
CREATE TABLE condicion_iva (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 descripcion varchar(80) NOT NULL UNIQUE
);
CREATE TABLE tipo_moneda (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(3) NOT NULL UNIQUE, descripcion varchar(60) NOT NULL
);
CREATE TABLE articulo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 codigo varchar(30) NOT NULL UNIQUE, descripcion varchar(150) NOT NULL,
 alicuota_iva numeric(5,2) NOT NULL CHECK (alicuota_iva BETWEEN 0 AND 100)
);
CREATE TABLE lista_precio_articulo (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 articulo_id bigint NOT NULL REFERENCES articulo(id),
 tipo_moneda_id bigint NOT NULL REFERENCES tipo_moneda(id),
 precio numeric(15,2) NOT NULL CHECK (precio >= 0),
 UNIQUE (articulo_id, tipo_moneda_id)
);
CREATE TABLE factura_venta (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version bigint NOT NULL DEFAULT 0, fecha date NOT NULL,
 cliente_id bigint NOT NULL REFERENCES cliente(id),
 condicion_iva_id bigint NOT NULL REFERENCES condicion_iva(id),
 punto_venta_id bigint NOT NULL REFERENCES punto_venta(id),
 tipo_moneda_id bigint NOT NULL REFERENCES tipo_moneda(id),
 estado varchar(10) NOT NULL CHECK (estado IN ('EMITIDA','ANULADA')),
 fecha_anulacion timestamptz, observaciones varchar(1000),
 neto numeric(19,2) NOT NULL CHECK (neto >= 0),
 iva numeric(19,2) NOT NULL CHECK (iva >= 0),
 total numeric(19,2) NOT NULL CHECK (total = neto + iva),
 CHECK ((estado = 'ANULADA' AND fecha_anulacion IS NOT NULL)
     OR (estado = 'EMITIDA' AND fecha_anulacion IS NULL))
);
CREATE TABLE factura_detalle (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 factura_id bigint NOT NULL REFERENCES factura_venta(id),
 lista_precio_articulo_id bigint NOT NULL REFERENCES lista_precio_articulo(id),
 descripcion varchar(150) NOT NULL,
 cantidad numeric(9,3) NOT NULL CHECK (cantidad > 0),
 precio_unitario numeric(15,2) NOT NULL CHECK (precio_unitario >= 0),
 alicuota_iva numeric(5,2) NOT NULL CHECK (alicuota_iva BETWEEN 0 AND 100),
 neto numeric(19,2) NOT NULL CHECK (neto >= 0),
 iva numeric(19,2) NOT NULL CHECK (iva >= 0),
 total numeric(19,2) NOT NULL CHECK (total = neto + iva)
);
CREATE INDEX idx_factura_cliente ON factura_venta(cliente_id);
CREATE INDEX idx_factura_fecha ON factura_venta(fecha);
CREATE INDEX idx_factura_estado ON factura_venta(estado);
CREATE INDEX idx_detalle_factura ON factura_detalle(factura_id);
