package ar.edu.utn.facturacion;

import ar.edu.utn.facturacion.config.DemoH2ClientesDescuentosConfig;
import java.sql.*;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.core.io.support.EncodedResource;
import org.springframework.jdbc.datasource.init.ScriptUtils;
import static org.assertj.core.api.Assertions.*;

class ClienteDescuentoMigracionTest {
    @Test void migraDatosPreviosYAmpliaPreciosSinReemplazarHistorialNiPreciosCargados() throws Exception {
        try(var c=DriverManager.getConnection("jdbc:h2:mem:migrar_cliente_descuentos;MODE=PostgreSQL"); var s=c.createStatement()) {
            s.execute("CREATE TABLE cliente(id bigint primary key,nombre varchar(120),documento varchar(30))");
            s.execute("INSERT INTO cliente VALUES(1,'Cliente histórico','DEMO-001')");
            s.execute("CREATE TABLE factura_venta(id bigint primary key,cliente_id bigint,neto numeric(19,2),iva numeric(19,2),total numeric(19,2),cliente_domicilio varchar(250))");
            s.execute("INSERT INTO factura_venta VALUES(1,1,1000,210,1210,'Domicilio histórico')");
            s.execute("CREATE TABLE factura_detalle(id bigint primary key,neto numeric(19,2))");
            s.execute("INSERT INTO factura_detalle VALUES(1,1000)");
            ScriptUtils.executeSqlScript(c,new EncodedResource(new ClassPathResource("db/migration/V10__cliente_y_descuento_general.sql"),"UTF-8"));
            s.execute("UPDATE cliente SET nombre='Cliente actualizado'");
            DemoH2ClientesDescuentosConfig.actualizarHistoricos(c);
            DemoH2ClientesDescuentosConfig.actualizarHistoricos(c);
            try(var r=s.executeQuery("SELECT cliente_nombre,cliente_documento,cliente_domicilio,total,importe_descuento,tipo_descuento FROM factura_venta")) {
                assertThat(r.next()).isTrue(); assertThat(r.getString(1)).isEqualTo("Cliente histórico");
                assertThat(r.getString(2)).isEqualTo("DEMO-001"); assertThat(r.getString(3)).isEqualTo("Domicilio histórico");
                assertThat(r.getBigDecimal(4)).isEqualByComparingTo("1210"); assertThat(r.getBigDecimal(5)).isEqualByComparingTo("0"); assertThat(r.getString(6)).isEqualTo("SIN_DESCUENTO");
            }
            try(var r=s.executeQuery("SELECT tipo_documento,condicion_iva_receptor_id FROM cliente")) { assertThat(r.next()).isTrue(); assertThat(r.getObject(1)).isNull(); assertThat(r.getObject(2)).isNull(); }
            s.execute("CREATE TABLE articulo(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,codigo varchar(30) UNIQUE,descripcion varchar(150),alicuota_iva numeric(5,2))");
            s.execute("CREATE TABLE tipo_moneda(id bigint primary key,codigo varchar(3))"); s.execute("INSERT INTO tipo_moneda VALUES(1,'ARS'),(2,'USD')");
            s.execute("CREATE TABLE lista_precio(id bigint primary key)"); s.execute("INSERT INTO lista_precio VALUES(1),(2)");
            s.execute("CREATE TABLE lista_precio_articulo(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,articulo_id bigint,tipo_moneda_id bigint,precio numeric(15,2),lista_precio_id bigint,UNIQUE(articulo_id,tipo_moneda_id,lista_precio_id))");
            var semilla=new EncodedResource(new ClassPathResource("db/migration/V11__ampliar_catalogo_demostracion.sql"),"UTF-8");
            ScriptUtils.executeSqlScript(c,semilla);
            s.execute("UPDATE lista_precio_articulo SET precio=123.45 WHERE id=1");
            ScriptUtils.executeSqlScript(c,semilla);
            try(var r=s.executeQuery("SELECT count(*) FROM articulo")) { assertThat(r.next()).isTrue(); assertThat(r.getInt(1)).isEqualTo(8); }
            try(var r=s.executeQuery("SELECT count(*) FROM lista_precio_articulo")) { assertThat(r.next()).isTrue(); assertThat(r.getInt(1)).isEqualTo(16); }
            try(var r=s.executeQuery("SELECT precio FROM lista_precio_articulo WHERE id=1")) { assertThat(r.next()).isTrue(); assertThat(r.getBigDecimal(1)).isEqualByComparingTo("123.45"); }
        }
    }
}
