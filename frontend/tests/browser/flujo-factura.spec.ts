test('primero exige la lista y consulta únicamente sus artículos; al reabrir conserva la lista de la factura', async ({ page, request }) => {
  expect((await request.put('/api/listas-precio/2/precios', { data: { articuloId:1,tipoMonedaId:1,precio:800 } })).status()).toBe(200);
  const consultas: URL[] = [];
  page.on('request', r => { const url = new URL(r.url()); if (url.pathname.startsWith('/api/catalogos')) consultas.push(url); });
  const inicial = page.waitForResponse(r => new URL(r.url()).pathname === '/api/catalogos');
  await page.goto('/');
  const metadatos = await (await inicial).json(); expect(metadatos.articulos).toEqual([]); expect(metadatos.precios).toEqual([]);
  await page.locator('#new-invoice').click(); await page.locator('#add-line').click();
  const lista = page.locator('#price-filters [name=listaPrecioId]');
  await expect(page.locator('#price-status')).toContainText('Seleccioná una lista');
  await expect(lista).toHaveValue(''); await expect(page.locator('#price-results')).not.toBeVisible();
  await expect(page.locator('#price-filters [name=q]')).toBeDisabled();
  expect(consultas.filter(u => u.pathname === '/api/catalogos/precios')).toHaveLength(0);
  expect(consultas.filter(u => u.pathname === '/api/catalogos').every(u => u.searchParams.get('incluirArticulos') === 'false')).toBe(true);
  await page.screenshot({ path:'../tmp/browser-results/primero-lista-precios.png',fullPage:true });
  await page.setViewportSize({ width:390,height:844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path:'../tmp/browser-results/primero-lista-precios-movil.png',fullPage:true });
  await page.setViewportSize({ width:1280,height:900 });
  await lista.selectOption('2');
  expect(consultas.filter(u => u.pathname === '/api/catalogos/precios')).toHaveLength(0);
  await page.locator('#price-filters button[type=submit]').click();
  await expect(page.locator('#price-rows [data-price-list="2"]').first()).toBeVisible();
  await expect(page.locator('#price-rows [data-price-list="1"]')).toHaveCount(0);
  expect(consultas.filter(u => u.pathname === '/api/catalogos/precios').every(u => u.searchParams.get('listaPrecioId') === '2')).toBe(true);
  const cantidadConsultas = consultas.length;
  await lista.selectOption(''); await expect(page.locator('#price-status')).toContainText('Seleccioná una lista');
  await expect(page.locator('#price-rows [data-price-list="2"]').first()).toBeVisible();
  await expect(page.locator('#price-rows [data-price-list="2"]').first()).toBeDisabled(); expect(consultas).toHaveLength(cantidadConsultas);
  const vacia = await request.post('/api/listas-precio',{ data:{ nombre:`Vacía selección ${Date.now()}` } });
  const { id: listaVacia } = await vacia.json();
  await page.locator('[data-close=price-dialog]').click(); await page.locator('#add-line').click();
  await expect(lista.locator(`option[value="${listaVacia}"]`)).toHaveCount(1);
  await lista.selectOption(String(listaVacia));
  await page.locator('#price-filters button[type=submit]').click();
  await expect(page.locator('#price-status')).toContainText('No hay artículos con precio');
  await expect(page.locator('#price-results')).not.toBeVisible();
  await lista.selectOption('2'); await page.locator('#price-filters button[type=submit]').click();
  await page.locator('#price-rows [data-price-article="1"][data-price-list="2"]').click();
  await expect(page.locator('#price-dialog')).not.toBeVisible(); await page.locator('.line-quantity').fill('3');
  await page.locator('#add-line').click(); await expect(lista).toHaveValue('2');
  await page.locator('#price-filters button[type=submit]').click();
  await expect(page.locator('#price-rows [data-price-list="2"]').first()).toBeVisible();
  await expect(page.locator('#price-rows [data-price-list="1"]')).toHaveCount(0);
  await expect(page.locator('.line-quantity')).toHaveValue('3');
});

test('cambiar lista exige precios completos y confirmación; conserva cantidades, cliente y descuento', async ({ page, request }) => {
  for (const [articuloId,precio] of [[1,800],[2,150]]) expect((await request.put('/api/listas-precio/2/precios',{ data: { articuloId,tipoMonedaId:1,precio } })).status()).toBe(200);
  const creada = await request.post('/api/listas-precio',{ data: { nombre:`Incompleta ${Date.now()}` } });
  const listaFaltante: { id: number } = await creada.json();
  expect((await request.put(`/api/listas-precio/${listaFaltante.id}/precios`,{ data: { articuloId:1,tipoMonedaId:1,precio:500 } })).status()).toBe(200);
  await page.setViewportSize({ width:1366,height:1000 });
  await page.goto('/'); await page.locator('#new-invoice').click();
  const form = page.locator('#invoice-form');
  await form.locator('[name=tipoComprobante]').selectOption('11'); await form.locator('[name=clienteId]').selectOption('1');
  await expect(page.locator('#selected-client')).toContainText('Ana');
  await form.locator('[name=observaciones]').fill('Conservar al cambiar lista');
  await agregarArticulo(page,1); await page.locator('.line-quantity').fill('2');
  await agregarArticulo(page,2); await page.locator('.line-quantity').last().fill('3');
  await form.locator('[name=tipoDescuento]').selectOption('PORCENTAJE'); await form.locator('[name=valorDescuento]').fill('10');
  await expect(page.locator('#preview-total')).toHaveText('ARS 2.340,00');
  const consultar = async (lista: string) => {
    await page.locator('#change-price-list').click();
    await page.locator('#change-list-form [name=listaPrecioId]').selectOption(lista); await page.locator('#preview-price-list').click();
  };
  await consultar(String(listaFaltante.id));
  await expect(page.locator('#change-list-error')).toContainText('Lápiz');
  await expect(page.locator('#apply-price-list')).not.toBeVisible();
  await expect(form.locator('[name=listaPrecioId]')).toHaveValue('1'); await expect(page.locator('#preview-total')).toHaveText('ARS 2.340,00');
  await page.locator('[data-close=change-list-dialog]').click();
  await form.locator('[name=tipoDescuento]').selectOption('MONTO_FIJO'); await form.locator('[name=valorDescuento]').fill('2300');
  await consultar('2'); await expect(page.locator('#change-list-error')).toContainText('descuento');
  await expect(page.locator('#apply-price-list')).not.toBeVisible(); await expect(form.locator('[name=listaPrecioId]')).toHaveValue('1');
  await page.locator('[data-close=change-list-dialog]').click();
  await form.locator('[name=tipoDescuento]').selectOption('PORCENTAJE'); await form.locator('[name=valorDescuento]').fill('10');
  await consultar('2'); await expect(page.locator('#change-list-impact')).toContainText('ARS 1.845,00');
  await expect(page.locator('#change-list-rows tr')).toHaveCount(2); await expect(page.locator('#preview-total')).toHaveText('ARS 2.340,00');
  await page.locator('[data-close=change-list-dialog]').click(); await expect(form.locator('[name=listaPrecioId]')).toHaveValue('1');
  await consultar('2'); await expect(page.locator('#apply-price-list')).toBeVisible();
  await page.screenshot({ path:'../tmp/browser-results/cambio-lista-confirmacion.png',fullPage:true });
  await page.setViewportSize({ width:390,height:844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path:'../tmp/browser-results/cambio-lista-movil.png',fullPage:true });
  await page.setViewportSize({ width:1366,height:1000 });
  await page.locator('#apply-price-list').click(); await expect(page.locator('#change-list-dialog')).not.toBeVisible();
  await expect(form.locator('[name=listaPrecioId]')).toHaveValue('2'); await expect(page.locator('#preview-total')).toHaveText('ARS 1.845,00');
  await expect(page.locator('.line-quantity').first()).toHaveValue('2'); await expect(page.locator('.line-quantity').last()).toHaveValue('3');
  await expect(form.locator('[name=valorDescuento]')).toHaveValue('10'); await expect(form.locator('[name=clienteId]')).toHaveValue('1');
  await expect(form.locator('[name=observaciones]')).toHaveValue('Conservar al cambiar lista');
  await page.screenshot({ path:'../tmp/browser-results/factura-lista-actualizada.png',fullPage:true });
  const respuesta = page.waitForResponse(r => r.request().method()==='POST' && r.url().endsWith('/api/facturas'));
  await page.locator('#save-invoice').click(); const guardada = await respuesta; expect(guardada.status()).toBe(201);
  const factura: FacturaReporteDTO = await guardada.json(); expect(factura.listaPrecioId).toBe(2); expect(factura.total).toBe(1845);
  expect(factura.detalles.map(d=>d.precioUnitario)).toEqual([800,150]); expect(factura.detalles.map(d=>d.cantidad)).toEqual([2,3]);
  await request.delete(`/api/facturas/${factura.id}`);
});
