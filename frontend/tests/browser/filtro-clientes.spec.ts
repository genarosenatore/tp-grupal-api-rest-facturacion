import { test, expect } from '@playwright/test';
import type { CatalogosDTO } from '../../src/models/catalogos.dto';

test('el filtro reutiliza el buscador de clientes y conserva los otros filtros y el borrador', async ({ page, request }) => {
  const catalogo: CatalogosDTO = await (await request.get('/api/catalogos')).json();
  const clienteFactura = catalogo.clientes[0], clienteFiltro = catalogo.clientes.find(c => c.id !== clienteFactura.id)!;
  expect(clienteFiltro).toBeTruthy();
  await page.goto('/'); await page.locator('#new-invoice').click();
  await page.locator('#invoice-client').click();
  await page.locator('#client-filters [name=q]').fill(clienteFactura.documento);
  await page.locator('#client-filters [name=q]').press('Enter');
  await page.locator(`[data-client="${clienteFactura.id}"]`).click();
  await expect(page.locator('#client-dialog')).not.toBeVisible();
  await page.locator('#invoice-form [name=observaciones]').fill('Conservar este borrador al filtrar');
  await page.locator('[data-close=invoice-dialog]').click();
  await page.locator('#filters [name=estado]').selectOption('ANULADA');
  await page.locator('#filters [name=informadaArca]').selectOption('false');
  await page.locator('#filter-client').click();
  await expect(page.locator('#client-dialog')).toBeVisible();
  await expect(page.locator('#client-context')).toContainText('consultar sus facturas');
  await expect(page.locator('#client-filters [name=q]')).toHaveValue('');
  await expect(page.locator('#new-client')).not.toBeVisible();
  await expect(page.locator('[data-edit-client]')).toHaveCount(0);
  await page.locator('#client-filters [name=q]').fill(clienteFiltro.documento);
  await page.locator('#client-filters button[type=submit]').click();
  await expect(page.locator('#client-rows tr')).toHaveCount(1);
  await page.locator('#client-dialog').screenshot({ path:'../tmp/browser-results/filtro-cliente-explorador.png' });
  await page.setViewportSize({ width:390,height:844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('#client-dialog').screenshot({ path:'../tmp/browser-results/filtro-cliente-explorador-movil.png' });
  await page.setViewportSize({ width:1280,height:720 });
  await page.locator('[data-close=client-dialog]').click();
  await expect(page.locator('#filter-client')).toHaveValue('');
  await page.locator('#filter-client').focus(); await page.keyboard.press('Enter');
  await expect(page.locator('#client-filters [name=q]')).toHaveValue(clienteFiltro.documento);
  await page.locator('#client-filters button[type=submit]').click();
  const filtrado = page.waitForResponse(r => {
    const url = new URL(r.url()); return url.pathname === '/api/facturas' && url.searchParams.get('clienteId') === String(clienteFiltro.id);
  });
  await page.locator(`[data-client="${clienteFiltro.id}"]`).click();
  await expect(page.locator('#client-dialog')).not.toBeVisible();
  await expect(page.locator('#filter-client')).toHaveValue(String(clienteFiltro.id));
  await expect(page.locator('#filter-instructions')).toContainText('cambios sin aplicar');
  await page.locator('#search-button').click(); expect((await filtrado).status()).toBe(200);
  await expect(page.locator('#filter-chips [data-remove-filter=clienteId]')).toContainText(clienteFiltro.nombre);
  await expect(page.locator('#filters [name=estado]')).toHaveValue('ANULADA');
  await expect(page.locator('#filters [name=informadaArca]')).toHaveValue('false');
  await page.locator('#new-invoice').click();
  await expect(page.locator('#invoice-client')).toHaveValue(String(clienteFactura.id));
  await expect(page.locator('#invoice-form [name=observaciones]')).toHaveValue('Conservar este borrador al filtrar');
  await page.locator('[data-close=invoice-dialog]').click();
  await page.locator('#filter-client').click(); await page.locator('#all-clients').click();
  await expect(page.locator('#client-dialog')).not.toBeVisible();
  await expect(page.locator('#filter-client')).toHaveValue('');
  await page.locator('#search-button').click();
  await expect(page.locator('#filter-chips [data-remove-filter=clienteId]')).toHaveCount(0);
  await expect(page.locator('#filters [name=estado]')).toHaveValue('ANULADA');
  await page.locator('#new-invoice').click(); await page.locator('#invoice-client').click();
  await expect(page.locator('#client-filters [name=q]')).toHaveValue(clienteFactura.documento);
  await expect(page.locator('#new-client')).toBeVisible(); await expect(page.locator('#all-clients')).not.toBeVisible();
});
