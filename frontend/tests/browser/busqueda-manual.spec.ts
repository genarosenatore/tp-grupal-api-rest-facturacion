import { test, expect } from '@playwright/test';

test('facturas, clientes y artículos consultan solo con Buscar, Enter o Limpiar', async ({ page }) => {
  const consultas = { facturas:0,clientes:0,precios:0 };
  page.on('request', request => {
    const url = new URL(request.url());
    if (url.pathname === '/api/facturas') consultas.facturas++;
    if (url.pathname === '/api/clientes') consultas.clientes++;
    if (url.pathname === '/api/catalogos/precios') consultas.precios++;
  });
  await page.goto('/'); await expect(page.locator('#search-button')).toBeEnabled();
  const iniciales = consultas.facturas;
  await page.locator('#filters [name=numero]').fill('999999');
  await page.locator('#filters [name=estado]').selectOption('ANULADA');
  await expect(page.locator('#filters [name=numero]')).toHaveValue('999999');
  await page.waitForTimeout(350); // Detecta también el antiguo debounce de 200 ms.
  expect(consultas.facturas).toBe(iniciales);
  await expect(page.locator('#filter-instructions')).toContainText('cambios sin aplicar');
  await page.locator('#filters [name=numero]').press('Enter');
  await expect(page.locator('#table-status')).toContainText('No hay facturas');
  expect(consultas.facturas).toBe(iniciales + 1);
  await page.locator('#filters button[type=reset]').click();
  await expect(page.locator('#filter-summary')).toHaveText('Todas las facturas');
  await expect(page.locator('#search-button')).toBeEnabled(); expect(consultas.facturas).toBe(iniciales + 2);
  await page.locator('#filter-client').click();
  await page.locator('#client-filters [name=q]').fill('Ana');
  await page.locator('#client-filters [name=documento]').fill('123');
  await page.waitForTimeout(350); expect(consultas.clientes).toBe(0);
  await expect(page.locator('#client-rows tr')).toHaveCount(0);
  await page.locator('#client-filters [name=q]').press('Enter');
  await expect(page.locator('#client-rows tr')).toHaveCount(1); expect(consultas.clientes).toBe(1);
  await page.locator('#client-filters [name=q]').fill('Bruno');
  await expect(page.locator('#client-filters [name=documento]')).toHaveValue('123');
  await expect(page.locator('#client-rows tr')).toHaveCount(1);
  await expect(page.locator('#client-rows tr')).toContainText('Ana');
  await expect(page.locator('#client-rows [data-client]')).toBeDisabled();
  await page.waitForTimeout(350); expect(consultas.clientes).toBe(1);
  await page.locator('#client-filters [name=q]').fill('Ana');
  await expect(page.locator('#client-rows [data-client]')).toBeEnabled();
  await page.locator('#client-filters button[type=reset]').click();
  await expect(page.locator('#client-filters [name=q]')).toHaveValue('');
  await expect(page.locator('#client-filters [name=documento]')).toHaveValue('');
  await expect(page.locator('#client-rows tr')).toHaveCount(1); expect(consultas.clientes).toBe(1);
  await page.locator('#client-filters button[type=submit]').click();
  await expect(page.locator('#client-status')).toContainText('Completá nombre o documento'); expect(consultas.clientes).toBe(1);
  await page.locator('#client-filters [name=q]').fill('Sin coincidencias');
  await page.locator('.client-results-heading').getByRole('button',{ name:'Ver todos los clientes',exact:true }).click();
  await expect(page.locator('#client-filters [name=q]')).toHaveValue('');
  await expect(page.locator('#client-rows tr').nth(1)).toBeVisible(); expect(consultas.clientes).toBe(2);
  await expect(page.locator('#client-dialog')).toBeVisible();
  await page.locator('[data-close=client-dialog]').click();
  await page.locator('#new-invoice').click(); await page.locator('#add-line').click();
  await page.locator('#price-filters [name=listaPrecioId]').selectOption('1');
  await page.locator('#price-filters [name=q]').fill('Cuaderno');
  await page.locator('#price-filters [name=iva]').fill('21');
  await page.waitForTimeout(350); expect(consultas.precios).toBe(0);
  await expect(page.locator('#price-rows tr')).toHaveCount(0);
  await page.locator('#price-filters [name=q]').press('Enter');
  await expect(page.locator('#price-rows tr')).toHaveCount(1); expect(consultas.precios).toBe(1);
  await page.locator('#price-filters [name=iva]').fill('10.5');
  await expect(page.locator('#price-filters [name=q]')).toHaveValue('Cuaderno');
  await expect(page.locator('#price-filters [name=listaPrecioId]')).toHaveValue('1');
  await expect(page.locator('#price-rows tr')).toHaveCount(1);
  await expect(page.locator('#price-rows [data-price-article]')).toBeDisabled();
  await page.waitForTimeout(350); expect(consultas.precios).toBe(1);
  await page.screenshot({ path:'../tmp/browser-results/resultados-con-filtros-pendientes.png',fullPage:true });
  await page.locator('#price-filters [name=iva]').fill('21');
  await expect(page.locator('#price-rows [data-price-article]')).toBeEnabled();
  await page.locator('#price-filters button[type=reset]').click();
  await expect(page.locator('#price-rows tr').nth(1)).toBeVisible(); expect(consultas.precios).toBe(2);
  await expect(page.locator('#price-filters [name=listaPrecioId]')).toHaveValue('1');
});
