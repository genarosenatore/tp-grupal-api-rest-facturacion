test('una consulta lenta del primer precio conserva la cantidad que se escribe mientras carga', async ({ page }) => {
  let liberar!: () => void, consultaIniciada!: () => void;
  const puerta = new Promise<void>(resolve => { liberar = resolve; });
  const iniciada = new Promise<void>(resolve => { consultaIniciada = resolve; });
  await page.route('**/api/catalogos/precios/2?**', async route => {
    const respuesta = await route.fetch(); consultaIniciada(); await puerta; await route.fulfill({ response: respuesta });
  });
  await page.goto('/'); await page.locator('#new-invoice').click();
  await page.locator('#invoice-form [name=tipoComprobante]').selectOption('11');
  await agregarArticulo(page,1);
  await page.locator('.line-article').selectOption('2'); await iniciada;
  await page.locator('.line-quantity').fill('7'); liberar();
  await expect(page.locator('#preview-total')).toHaveText('ARS 1.400,00');
  await expect(page.locator('.line-quantity')).toHaveValue('7');
  await expect(page.locator('#invoice-form [name=listaPrecioId]')).toHaveValue('1');
});

