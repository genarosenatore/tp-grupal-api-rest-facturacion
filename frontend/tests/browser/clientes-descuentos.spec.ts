import { test, expect } from '@playwright/test';
import { accionFactura } from './seleccion';
import type { ClienteDTO } from '../../src/models/catalogos.dto';
import type { FacturaReporteDTO } from '../../src/models/factura.dto';

test('ficha del cliente, exploradores con consulta vigente y descuento general conservan el historial', async ({ page, request }) => {
  const documento = String(80000000 + Date.now() % 10000000);
  await page.goto('/'); await expect(page.locator('#connection')).toHaveText('● API conectada');
  await page.locator('#new-invoice').click(); const form = page.locator('#invoice-form');
  await form.locator('[name=observaciones]').fill('Borrador con cliente y descuento');
  await form.locator('[name=clienteId]').click(); await expect(page.locator('#client-dialog')).toBeVisible();
  await page.locator('#new-client').click(); const ficha = page.locator('#client-edit-form');
  await ficha.locator('[name=nombre]').fill('Cliente descuento navegador');
  await ficha.locator('[name=documento]').fill(documento);
  await ficha.locator('[name=domicilio]').fill('Domicilio original 123');
  const clienteResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/clientes'));
  await page.locator('#save-client').click(); const cliente: ClienteDTO = await (await clienteResponse).json();
  await expect(page.locator('#client-edit-dialog')).not.toBeVisible();
  const consultaCliente = page.waitForResponse(r => r.url().endsWith(`/api/clientes/${cliente.id}`) && r.request().method() === 'GET');
  await page.locator(`[data-client="${cliente.id}"]`).click(); expect((await consultaCliente).status()).toBe(200);
  await expect(page.locator('#client-dialog')).not.toBeVisible();
  await expect(page.locator('#client-address')).toHaveText('Domicilio original 123');
  await expect(page.locator('#client-document')).toHaveText(`DNI ${documento}`);
  await expect(page.locator('#client-condition')).toHaveText('Consumidor final');
  await expect(page.locator('#client-data input, #client-data select')).toHaveCount(0);
  await expect(page.locator('.invoice-client-field #client-data')).toBeVisible();
  await page.screenshot({ path: '../tmp/browser-results/datos-cliente-documento.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../tmp/browser-results/datos-cliente-debajo-movil.png', fullPage: true });
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.locator('#add-line').click();
  await page.locator('#price-filters [name=listaPrecioId]').selectOption('1');
  await page.locator('#price-filters [name=q]').fill('A1');
  await page.locator('#price-filters button[type=submit]').click();
  await expect(page.locator('#price-rows [data-price-article="1"]')).toBeVisible();
  await page.route('**/api/catalogos/precios/1?**', route => route.fulfill({ status: 503, json: { mensaje: 'Precio temporalmente no disponible', errores: [] } }));
  await page.locator('#price-rows [data-price-article="1"]').click();
  await expect(page.locator('#price-alert')).toContainText('El servidor no pudo completar la operación');
  await expect(page.locator('#price-dialog')).toBeVisible(); await expect(form.locator('[name=observaciones]')).toHaveValue('Borrador con cliente y descuento');
  await page.unroute('**/api/catalogos/precios/1?**');
  const consultaPrecio = page.waitForResponse(r => r.url().includes('/api/catalogos/precios/1?'));
  await page.locator('#price-rows [data-price-article="1"]').click(); expect((await consultaPrecio).status()).toBe(200);
  await expect(page.locator('#price-dialog')).not.toBeVisible();
  await page.locator('.line-quantity').fill('2'); await page.locator('#add-line').click();
  await page.locator('#price-filters [name=q]').fill('A2');
  await page.locator('#price-filters button[type=submit]').click();
  await page.locator('#price-rows [data-price-article="2"]').click(); await expect(page.locator('#price-dialog')).not.toBeVisible();
  await page.locator('.line-quantity').last().fill('3');
  await form.locator('[name=tipoDescuento]').selectOption('PORCENTAJE'); await form.locator('[name=valorDescuento]').fill('10');
  await expect(page.locator('#preview-subtotal')).toHaveText('ARS 2.600,00');
  await expect(page.locator('#preview-discount')).toHaveText('ARS 260,00'); await expect(page.locator('#preview-total')).toHaveText('ARS 2.774,70');
  await form.locator('[name=tipoDescuento]').selectOption('MONTO_FIJO'); await form.locator('[name=valorDescuento]').fill('3000');
  expect(await form.locator('[name=valorDescuento]').evaluate((v: HTMLInputElement) => v.validity.customError)).toBe(true);
  await form.locator('[name=valorDescuento]').fill('260'); await expect(page.locator('#preview-total')).toHaveText('ARS 2.774,70');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: '../tmp/browser-results/descuento-general-movil.png', fullPage: true });
  await page.setViewportSize({ width: 1366, height: 1000 });
  await page.screenshot({ path: '../tmp/browser-results/descuento-general-escritorio.png', fullPage: true });
  const creadaResponse = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/api/facturas'));
  await page.locator('#save-invoice').click(); const respuesta = await creadaResponse;
  expect(respuesta.status()).toBe(201); const enviada = respuesta.request().postDataJSON();
  expect(enviada.tipoDocumentoReceptor).toBeUndefined(); expect(enviada.condicionIvaReceptorId).toBeUndefined(); expect(enviada.clienteDomicilio).toBeUndefined();
  const factura: FacturaReporteDTO = await respuesta.json(); expect(factura.importeDescuento).toBe(260); expect(factura.total).toBe(2774.7);
  await expect(page.locator('#invoice-dialog')).not.toBeVisible();
  await accionFactura(page,factura.id,'edit');
  await expect(form.locator('[name=tipoDescuento]')).toHaveValue('MONTO_FIJO'); await expect(form.locator('[name=valorDescuento]')).toHaveValue('260');
  await expect(page.locator('#preview-total')).toHaveText('ARS 2.774,70');
  await page.locator('[data-close=invoice-dialog]').click();
  const cambio = await request.put(`/api/clientes/${cliente.id}`, { data: { nombre: 'Nombre actualizado', documento, tipoDocumento: 96, condicionIvaReceptorId: 5, domicilio: 'Domicilio nuevo 987' } });
  expect(cambio.status()).toBe(200);
  const historica: FacturaReporteDTO = await (await request.get(`/api/facturas/${factura.id}`)).json();
  expect(historica.clienteNombre).toBe('Cliente descuento navegador'); expect(historica.clienteDomicilio).toBe('Domicilio original 123');
  await page.locator(`[data-detail="${factura.id}"]`).click();
  await expect(page.locator('#detail-content')).toContainText('Cliente descuento navegador'); await expect(page.locator('#detail-content')).toContainText('Descuento general');
  await request.delete(`/api/facturas/${factura.id}`);
});
